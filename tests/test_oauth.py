    def test_anthropic_http_matches_reference_profile_preserving_prompt(self):
        credentials = Mock(get=lambda _: {"access_token": "token"})
        with patch.object(oauth, "open_request", return_value=claude_sse()) as send:
            result = oauth.OAuthTransport("anthropic-oauth", credentials).send({"model": "claude-test", "messages": MESSAGES})
        request = send.call_args.args[0]
        self.assertEqual(send.call_count, 1)
        self.assertEqual(request.full_url, oauth.ENDPOINTS["anthropic-oauth"])
        self.assertEqual(json.loads(request.data)["max_tokens"], 64000)
        self.assertTrue(json.loads(request.data)["stream"])
        self.assertEqual(request.get_header("Authorization"), "Bearer token")
        self.assertNotIn("X-api-key", request.headers)
        self.assertEqual(request.get_header("Anthropic-beta"), oauth.CLAUDE_BETAS)
        self.assertEqual(request.get_header("Anthropic-dangerous-direct-browser-access"), "true")
        self.assertEqual(request.get_header("Accept"), "text/event-stream, application/json")
        self.assertEqual(json.loads(request.data)["system"][1:], [{"type": "text", "text": "robot instructions"}])
        self.assertEqual(result["request_profile"], oauth.CLAUDE_COMPAT_VERSION)
        self.assertEqual(result["choices"][0]["finish_reason"], "end_turn")
        self.assertEqual(result["choices"][0]["message"]["content"], "OK")
        self.assertEqual(result["usage"]["completion_tokens"], 2)
        self.assertEqual(result["output_token_limit"], {"policy": "configured", "max_tokens": 64000})

