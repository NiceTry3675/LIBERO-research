    def test_failed_refresh_preserves_credential_file(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "auth.json"
            path.write_text(json.dumps({"access_token": "old", "refresh_token": "secret", "client_id": "c", "expires_at": 1}))
            path.chmod(0o600)
            before = path.read_bytes()
            with patch.object(oauth, "open_request", side_effect=HTTPError("secret", 400, "secret", {}, None)):
                with self.assertRaises(oauth.OAuthError) as raised:
                    oauth.Credentials("openai-oauth", path).get()
                self.assertNotIn("secret", str(raised.exception))
            self.assertEqual(path.read_bytes(), before)

    def test_private_file_and_rotated_refresh_are_persisted(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "auth.json"
            path.write_text(json.dumps({"access_token": "old", "refresh_token": "refresh-old", "client_id": "test",
                                        "expires_at": 1}))
            path.chmod(0o600)
            with patch.object(oauth, "open_request", return_value=io.BytesIO(json.dumps(
                    {"access_token": "new", "refresh_token": "refresh-new", "expires_in": 3600}).encode())) as send:
                auth = oauth.Credentials("openai-oauth", path)
                self.assertEqual(auth.get()["access_token"], "new")
                self.assertEqual(auth.get("old")["access_token"], "new")
                self.assertEqual(send.call_count, 1)
            self.assertEqual(json.loads(path.read_text())["refresh_token"], "refresh-new")
            self.assertEqual(path.stat().st_mode & 0o777, 0o600)
            path.chmod(0o644)
            with self.assertRaises(oauth.OAuthError):
                auth.get()
            path.chmod(0o600)
            link = Path(directory) / "link.json"
            link.symlink_to(path)
            with self.assertRaises(oauth.OAuthError):
                oauth.Credentials("openai-oauth", link).get()

    def test_multiple_workers_refresh_once(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "auth.json"
            path.write_text(json.dumps({"access_token": "old", "refresh_token": "r", "client_id": "c", "expires_at": 1}))
            path.chmod(0o600)
            results = []
            def refresh(*args):
                time.sleep(0.02)
                return io.BytesIO(b'{"access_token":"new","expires_in":3600}')
            with patch.object(oauth, "open_request", side_effect=refresh) as send:
                workers = [threading.Thread(target=lambda: results.append(oauth.Credentials("openai-oauth", path).get()))
                           for _ in range(4)]
                for worker in workers:
                    worker.start()
                for worker in workers:
                    worker.join()
                self.assertEqual(send.call_count, 1)
            self.assertEqual(len(results), 4)

