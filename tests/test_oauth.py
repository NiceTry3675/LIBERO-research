    def test_oauth_config_and_resume_mismatch(self):
        args = argparse.Namespace(repo=ROOT/"third_party/robodawn", manifest=ROOT/"robodawn_site/reproduction_manifest.json",
            task="adjust_bottle", episodes=1, start_episode=0, output=None, no_video=True, tier="flex",
            robotwin_root=Path("/content/RoboTwin"), variant="baseline", checker=None, threshold=.5,
            max_steps=3, empty_grasp_limit=0, max_tokens=8000, backend="openai-oauth", model="gpt-test",
            oauth_credentials=None, reasoning_effort="high")
        config, flags = relay.configuration(args)
        self.assertEqual(config["model"], "gpt-test")
        self.assertEqual(config["tier"], "oauth")
        self.assertEqual(flags[flags.index("--model") + 1], "gpt-test")
        self.assertFalse(config["oauth"]["max_output_tokens_sent"])
        self.assertIsNone(config["max_tokens"])
        claude_args = argparse.Namespace(**{**vars(args), "backend": "anthropic-oauth", "model": "claude-opus-5-5"})
        self.assertEqual(relay.configuration(claude_args)[0]["oauth"]["request_profile"], oauth.CLAUDE_COMPAT_VERSION)
        with tempfile.TemporaryDirectory() as directory:
            args.output = Path(directory)
            (args.output/"relay_config.json").write_text(json.dumps(config))
            args.model = "gpt-other"
            with self.assertRaisesRegex(ValueError, "different conditions"):
                relay.configuration(args)
        # Older Vertex metadata has no backend/oauth keys and must still resume.
        args.backend, args.model, args.reasoning_effort, args.output = "vertex", None, None, None
        config, _ = relay.configuration(args)
        with tempfile.TemporaryDirectory() as directory:
            args.output = Path(directory)
            (args.output/"relay_config.json").write_text(json.dumps(config))
            self.assertEqual(relay.configuration(args)[0]["model"], relay.MODEL)

